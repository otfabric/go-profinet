// Package typed is the complete, generated Go model of every GSDML schema
// version go-profinet has the reference schemas of (Versions): a struct
// for every complex type, typed fields for every attribute and element, a
// reflection-free decoder and encoder, and a validator that checks a
// document against the schema of its version (structure, simple types
// with every facet, defaults and fixed values, identity constraints)
// without reading any schema at run time.
//
// The types are deduplicated across versions: a type that is the same in
// several versions is one struct; a type that differs is one struct per
// variant, named after the first version of the variant (ModuleItemT_V231).
// The packages gsdml/versions/vNNN give each version its own names
// (v246.ModuleItemT) as aliases of these structs.
//
// The structs are generated by internal/cmd/gsdmlc from the reference
// schemas (docs/CODEGEN.md); do not edit the zz_ files.
//
// The validator agrees with libxml2's xmllint on every file of the
// differential test (TestXSDDifferential); the limits of that evidence are
// in LIMITATIONS.md.
package typed

import (
	"fmt"
	"io"
	"regexp"

	profinet "github.com/otfabric/go-profinet"
)

// Versioned is a typed document of some schema version: a *Document[T]
// for the root type T of that version.
type Versioned interface {
	// SchemaVersion is the GSDML version, "2.46".
	SchemaVersion() string
	// Encode writes the document as XML.
	Encode(w io.Writer) error
	// RootElement returns the root (*ISO15745Profile_Vnnn).
	RootElement() any
}

// root is what a generated root type implements.
type root interface {
	encodeAs(e *encoder, ns, local string)
}

// Document is a typed GSDML document: the root element of a schema
// version with the attributes of the root that are not in the schema
// (xsi:schemaLocation).
type Document[T root] struct {
	// Version is the schema version the document was parsed as.
	Version string
	Root    T
	// SchemaLocation is the root's xsi:schemaLocation, written back by
	// Encode; empty writes none.
	SchemaLocation string
}

// SchemaVersion returns d.Version.
func (d *Document[T]) SchemaVersion() string { return d.Version }

// RootElement returns d.Root.
func (d *Document[T]) RootElement() any { return d.Root }

// Marshal returns the document as XML.
func (d *Document[T]) Marshal() []byte {
	e := newEncoder()
	e.rootAttrs = d.rootAttrs()
	d.Root.encodeAs(e, nsDeviceProfile, "ISO15745Profile")
	return e.bytes()
}

func (d *Document[T]) rootAttrs() []rootAttr {
	if d.SchemaLocation == "" {
		return nil
	}
	return []rootAttr{{ns: nsXSI, local: "schemaLocation", value: d.SchemaLocation}}
}

// Encode writes the document as XML.
func (d *Document[T]) Encode(w io.Writer) error {
	_, err := w.Write(d.Marshal())
	return err
}

// Validate encodes the document and validates the XML against the schema
// of d.Version: the in-memory model, after any change, is checked as the
// document it writes.
func (d *Document[T]) Validate() error {
	return ValidateVersion(d.Marshal(), d.Version)
}

var schemaLocation = regexp.MustCompile(`GSDML-DeviceProfile-[vV]([0-9]+\.[0-9]+)\.xsd`)

// DetectVersion returns the schema version a document names in its root's
// xsi:schemaLocation ("2.46"), or ErrUnknownVersion.
func DetectVersion(data []byte) (string, error) {
	n, err := ParseNode(data)
	if err != nil {
		return "", err
	}
	return detect(n)
}

func detect(n *Node) (string, error) {
	loc, ok := n.Attr(nsXSI, "schemaLocation")
	if !ok {
		loc, ok = n.Attr(nsXSI, "noNamespaceSchemaLocation")
	}
	if ok {
		if m := schemaLocation.FindStringSubmatch(loc); m != nil {
			return m[1], nil
		}
	}
	return "", fmt.Errorf("%w: the root names no GSDML-DeviceProfile schema in xsi:schemaLocation", ErrUnknownVersion)
}

// Versions returns the schema versions this package has, oldest first.
func Versions() []string { return sortedVersions(tables) }

// Validate validates a document against the schema of the version it
// names. The error is a *SchemaError when the document is not valid, and
// matches ErrUnknownVersion when it names no known version.
func Validate(data []byte) error {
	n, err := ParseNode(data)
	if err != nil {
		return err
	}
	v, err := detect(n)
	if err != nil {
		return err
	}
	return validateNode(n, v)
}

// ValidateVersion validates a document against the schema of version,
// whatever version the document names.
func ValidateVersion(data []byte, version string) error {
	n, err := ParseNode(data)
	if err != nil {
		return err
	}
	return validateNode(n, version)
}

// Parse validates a document against the schema of the version it names
// and returns its typed model.
func Parse(data []byte) (Versioned, error) {
	n, err := ParseNode(data)
	if err != nil {
		return nil, err
	}
	v, err := detect(n)
	if err != nil {
		return nil, err
	}
	return parseNode(n, v, true)
}

// ParseVersion is Parse with the version given: the document is
// validated against, and decoded as, that version.
func ParseVersion(data []byte, version string) (Versioned, error) {
	n, err := ParseNode(data)
	if err != nil {
		return nil, err
	}
	return parseNode(n, version, true)
}

// Decode returns the typed model of a document as the version it names
// without validating it. It fails on what the model cannot hold (an
// element or attribute not in the schema, a value that does not parse as
// its type), and accepts what only validation rejects (order, counts,
// facets, identity constraints).
func Decode(data []byte) (Versioned, error) {
	n, err := ParseNode(data)
	if err != nil {
		return nil, err
	}
	v, err := detect(n)
	if err != nil {
		return nil, err
	}
	return parseNode(n, v, false)
}

func parseNode(n *Node, version string, validate bool) (Versioned, error) {
	if versionIndex(tables, version) < 0 {
		return nil, fmt.Errorf("%w: %q", ErrUnknownVersion, version)
	}
	if validate {
		if err := validateNode(n, version); err != nil {
			return nil, err
		}
	}
	if err := checkRoot(n); err != nil {
		return nil, err
	}
	d, ok, err := build(version, n)
	if !ok {
		return nil, fmt.Errorf("%w: %q", ErrUnknownVersion, version)
	}
	if err != nil {
		return nil, err
	}
	return d, nil
}

func checkRoot(n *Node) error {
	if n.Name.Space != nsDeviceProfile || n.Name.Local != "ISO15745Profile" {
		return fmt.Errorf("typed: %w: the root is {%s}%s, not ISO15745Profile", profinet.ErrMalformed, n.Name.Space, n.Name.Local)
	}
	return nil
}

// rootAttr is an attribute the encoder writes on the root element.
type rootAttr struct {
	ns, local, value string
}

// DecodeVersion is Decode with the version given.
func DecodeVersion(data []byte, version string) (Versioned, error) {
	n, err := ParseNode(data)
	if err != nil {
		return nil, err
	}
	return parseNode(n, version, false)
}

// ParseAs is ParseVersion for a known root type T (ISO15745Profile_V246):
// the facades (gsdml/versions/vNNN) use it. It decodes with T's decoder
// only, so that a program using one version links that version's types.
func ParseAs[T any, P buildable[T]](data []byte, version string) (*Document[P], error) {
	return decodeAs[T, P](data, version, true)
}

// DecodeAs is DecodeVersion for a known root type.
func DecodeAs[T any, P buildable[T]](data []byte, version string) (*Document[P], error) {
	return decodeAs[T, P](data, version, false)
}

func decodeAs[T any, P buildable[T]](data []byte, version string, validate bool) (*Document[P], error) {
	n, err := ParseNode(data)
	if err != nil {
		return nil, err
	}
	if versionIndex(tables, version) < 0 {
		return nil, fmt.Errorf("%w: %q", ErrUnknownVersion, version)
	}
	if validate {
		if err := validateNode(n, version); err != nil {
			return nil, err
		}
	}
	if err := checkRoot(n); err != nil {
		return nil, err
	}
	return buildDocument[T, P](n, version)
}

type buildable[T any] interface {
	*T
	root
	from(n *Node, b *builder) *T
}

// buildDocument decodes a tree as the root type of a version.
func buildDocument[T any, P buildable[T]](n *Node, version string) (*Document[P], error) {
	b := &builder{}
	r := P(new(T)).from(n, b)
	if b.err != nil {
		return nil, b.err
	}
	d := &Document[P]{Version: version, Root: P(r)}
	d.SchemaLocation, _ = n.Attr(nsXSI, "schemaLocation")
	return d, nil
}

func asVersioned[P root](d *Document[P], err error) (Versioned, error) {
	if err != nil {
		return nil, err
	}
	return d, nil
}
