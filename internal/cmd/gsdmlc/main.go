// Command gsdmlc is the GSDML schema compiler: it reads the reference
// schemas of every GSDML version (the private otfabric/profinet-gsdml-
// schema, make gsdml-schemas) and generates
//
//   - gsdml/typed/zz_types.go: a Go struct for every complex type, with
//     its reflection-free decoder and encoder, deduplicated across
//     versions (one struct per representation variant), and a named type
//     with constants for every enumeration;
//   - gsdml/typed/zz_tables.go: the validation tables (simple types with
//     their facets, content automata, attribute uses, identity
//     constraints) of every version, deduplicated;
//   - gsdml/typed/zz_versions.go: the version registry;
//   - gsdml/typed/zz_samples_test.go: a sample node per struct, which the
//     tests build and encode;
//   - gsdml/versions/vNNN/zz_facade.go: one package per version with the
//     version's names for the shared types;
//   - docs/GSDML-TYPED.md: the inventory, the deduplication figures and
//     the evolution of every type across versions.
//
// No schema text is copied: names, structure, facets and values only.
//
//	go run ./internal/cmd/gsdmlc -schemas .gsdml-schemas/xsd          # write
//	go run ./internal/cmd/gsdmlc -schemas .gsdml-schemas/xsd -check   # compare
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/otfabric/go-profinet/internal/xsdc"
)

func main() {
	schemas := flag.String("schemas", ".gsdml-schemas/xsd", "the xsd directory of the reference schemas")
	out := flag.String("out", ".", "the repository root")
	check := flag.Bool("check", false, "fail when the generated files differ")
	flag.Parse()
	if err := run(*schemas, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gsdmlc:", err)
		os.Exit(1)
	}
}

func run(schemas, out string, check bool) error {
	c, err := xsdc.LoadCorpus(schemas)
	if err != nil {
		return err
	}
	g, err := newGen(c)
	if err != nil {
		return err
	}
	files, err := g.generate()
	if err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var stale []string
	for _, n := range names {
		p := filepath.Join(out, n)
		if check {
			old, err := os.ReadFile(p)
			if err != nil || !bytes.Equal(old, files[n]) {
				stale = append(stale, n)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, files[n], 0o644); err != nil {
			return err
		}
	}
	if check {
		// a facade of a version that no longer exists
		dirs, _ := filepath.Glob(filepath.Join(out, "gsdml/versions/v*"))
		for _, d := range dirs {
			rel, _ := filepath.Rel(out, filepath.Join(d, "zz_facade.go"))
			if _, ok := files[filepath.ToSlash(rel)]; !ok {
				stale = append(stale, rel+" (no such version)")
			}
		}
		if len(stale) > 0 {
			return fmt.Errorf("generated files differ from the schemas (run make gsdml-generate): %s", strings.Join(stale, ", "))
		}
	}
	return nil
}

const header = "// Code generated by gsdmlc from the GSDML reference schemas. DO NOT EDIT.\n\n"

// Namespaces and their Go prefixes.
const (
	nsDeviceProfile = "http://www.profibus.com/GSDML/2003/11/DeviceProfile"
	nsPrimitives    = "http://www.profibus.com/GSDML/2003/11/Primitives"
	nsDsig          = "http://www.w3.org/2000/09/xmldsig#"
	nsXades         = "http://uri.etsi.org/01903/v1.3.2#"
	nsXML           = "http://www.w3.org/XML/1998/namespace"
	nsXS            = "http://www.w3.org/2001/XMLSchema"
)

var nsPrefix = map[string]string{
	nsDeviceProfile: "",
	nsPrimitives:    "",
	nsDsig:          "Ds",
	nsXades:         "Xades",
	nsXML:           "XML",
	nsXS:            "XS",
}

var nsConst = map[string]string{
	"":              `""`,
	nsDeviceProfile: "nsDeviceProfile",
	nsPrimitives:    "nsPrimitives",
	nsDsig:          "nsDsig",
	nsXades:         "nsXades",
	nsXML:           "nsXML",
}

type repKey struct {
	comp  xsdc.Component
	class string
}

type goStruct struct {
	name     string // in package typed
	base     string // the version-independent name (facade alias)
	comp     xsdc.Component
	rep      *xsdc.ComplexType
	vi       int   // the version of the representative
	versions []int // every version of this variant
	shape    *xsdc.Shape
	fields   []*goField
}

type fieldKind int

const (
	fAttr fieldKind = iota
	fElem
	fValue
	fAny
	fAnyAttr
	fContent
)

type goField struct {
	name   string
	kind   fieldKind
	goType string
	// attribute or element
	ns, local string
	simple    *xsdc.SimpleType // simple-typed attribute, element or value
	ptr, many bool
	raw       bool
	child     *goStruct
	def       *string
	// order is the index among the content fields of an ordered struct
	order int
}

type goEnum struct {
	name   string
	comp   xsdc.Component
	values []string // across versions, in first appearance order
	consts map[string]string
	// perVersion: the values of the enumeration in each version
	perVersion [][]string
}

type gen struct {
	c        *xsdc.Corpus
	ix       []*xsdc.Index
	rep      *xsdc.Variants
	full     *xsdc.Variants
	codec    *xsdc.Variants
	structs  []*goStruct
	structOf map[repKey]*goStruct
	enums    map[xsdc.Component]*goEnum
	enumList []*goEnum
	used     map[string]bool
	roots    []*goStruct // per version
}

// reserved are the identifiers of package typed's hand-written code.
var reserved = []string{
	"Node", "Issue", "SchemaError", "Document", "Versioned", "Integer", "Decimal", "Parse", "ParseVersion",
	"ParseAs", "Decode", "DecodeVersion", "Validate", "ValidateVersion", "DetectVersion", "Versions",
	"ParseNode", "MaxDocumentSize", "MaxElements", "MaxDepth", "MaxIssues", "ErrUnknownVersion",
}

func newGen(c *xsdc.Corpus) (*gen, error) {
	g := &gen{c: c, structOf: map[repKey]*goStruct{}, enums: map[xsdc.Component]*goEnum{}, used: map[string]bool{}}
	for _, r := range reserved {
		g.used[r] = true
	}
	for _, s := range c.Sets {
		ix, err := xsdc.IndexOf(s)
		if err != nil {
			return nil, err
		}
		g.ix = append(g.ix, ix)
	}
	var err error
	if g.rep, err = xsdc.Analyze(c, xsdc.Representation); err != nil {
		return nil, err
	}
	if g.codec, err = xsdc.Analyze(c, xsdc.Codec); err != nil {
		return nil, err
	}
	if g.full, err = xsdc.Analyze(c, xsdc.Full); err != nil {
		return nil, err
	}
	if err := g.plan(); err != nil {
		return nil, err
	}
	return g, nil
}

// ident makes an exported Go identifier of an XML name.
func ident(s string) string {
	var b strings.Builder
	for i, r := range s {
		ok := r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')
		if !ok {
			r = '_'
		}
		if i == 0 {
			if r >= 'a' && r <= 'z' {
				r -= 'a' - 'A'
			} else if r == '_' || (r >= '0' && r <= '9') {
				b.WriteString("X")
			}
		}
		b.WriteRune(r)
	}
	return b.String()
}

func baseName(comp xsdc.Component) string {
	prefix := nsPrefix[comp.Name.NS]
	if comp.Path == "" {
		return prefix + ident(comp.Name.Local)
	}
	p := strings.ReplaceAll(comp.Path, "#", "/")
	p = strings.ReplaceAll(p, "@", "/")
	segs := strings.Split(p, "/")
	for i, s := range segs {
		segs[i] = ident(s)
	}
	return prefix + strings.Join(segs, "_")
}

func digits(v string) string {
	return strconv.Itoa(xsdc.VersionNumber(v))
}

func (g *gen) unique(name string) string {
	n := name
	for i := 2; g.used[n]; i++ {
		n = name + "_" + strconv.Itoa(i)
	}
	g.used[n] = true
	return n
}

// plan names every struct and enumeration and lays out the fields.
func (g *gen) plan() error {
	// complex components in a stable order
	var comps []xsdc.Component
	for comp := range g.rep.Classes {
		if comp.Kind == "complex" && comp.Name.NS != nsXS {
			comps = append(comps, comp)
		}
	}
	sort.Slice(comps, func(i, j int) bool { return comps[i].String() < comps[j].String() })
	for _, comp := range comps {
		classes := g.rep.Classes[comp]
		var order []string
		byClass := map[string][]int{}
		for vi, cl := range classes {
			if cl == "" {
				continue
			}
			if _, ok := byClass[cl]; !ok {
				order = append(order, cl)
			}
			byClass[cl] = append(byClass[cl], vi)
		}
		base := baseName(comp)
		for _, cl := range order {
			vs := byClass[cl]
			name := base
			if len(order) > 1 {
				name = base + "_V" + digits(g.c.Versions[vs[0]])
			}
			st := &goStruct{name: g.unique(name), base: base, comp: comp, rep: g.ix[vs[0]].Complex[comp], vi: vs[0], versions: vs}
			g.structs = append(g.structs, st)
			g.structOf[repKey{comp, cl}] = st
		}
	}
	// enumerations
	var simples []xsdc.Component
	for comp := range g.rep.Classes {
		if comp.Kind == "simple" && comp.Name.NS != nsXS && comp.Path == "" {
			simples = append(simples, comp)
		}
	}
	sort.Slice(simples, func(i, j int) bool { return simples[i].String() < simples[j].String() })
	for _, comp := range simples {
		var en *goEnum
		for vi := range g.c.Sets {
			t, ok := g.ix[vi].Simple[comp]
			if !ok || xsdc.GoKind(t) != "enum" {
				continue
			}
			if en == nil {
				en = &goEnum{comp: comp, consts: map[string]string{}, perVersion: make([][]string, len(g.c.Sets))}
			}
			ws := t.EffectiveWhiteSpace()
			for _, v := range xsdc.EnumValues(t) {
				v = normalize(v, ws)
				en.perVersion[vi] = append(en.perVersion[vi], v)
				if _, ok := en.consts[v]; !ok {
					en.values = append(en.values, v)
					en.consts[v] = ""
				}
			}
		}
		if en == nil {
			continue
		}
		en.name = g.unique(baseName(comp))
		used := map[string]bool{}
		for _, v := range en.values {
			c := en.name + ident(constPart(v))
			if v == "" {
				c = en.name + "Empty"
			}
			for i := 2; used[c] || g.used[c]; i++ {
				c = en.name + ident(constPart(v)) + "_" + strconv.Itoa(i)
			}
			used[c] = true
			g.used[c] = true
			en.consts[v] = c
		}
		g.enums[comp] = en
		g.enumList = append(g.enumList, en)
	}
	// fields
	for _, st := range g.structs {
		if err := g.layout(st); err != nil {
			return fmt.Errorf("%s: %w", st.comp, err)
		}
	}
	// roots
	root := xsdc.Component{Kind: "element", Name: xsdc.QName{NS: nsDeviceProfile, Local: "ISO15745Profile"}}
	for vi := range g.c.Sets {
		e, ok := g.ix[vi].Element[root]
		if !ok || e.Complex == nil {
			return fmt.Errorf("version %s has no ISO15745Profile element", g.c.Versions[vi])
		}
		g.roots = append(g.roots, g.structFor(vi, e.Complex))
	}
	return nil
}

func constPart(v string) string {
	var b strings.Builder
	up := true
	for _, r := range v {
		ok := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')
		if !ok {
			up = true
			continue
		}
		if up && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		up = false
		b.WriteRune(r)
	}
	if b.Len() == 0 {
		return "Value"
	}
	return b.String()
}

func normalize(v, ws string) string {
	switch ws {
	case "collapse":
		return strings.Join(strings.FieldsFunc(v, func(r rune) bool { return r == ' ' || r == '\t' || r == '\r' || r == '\n' }), " ")
	case "replace":
		return strings.Map(func(r rune) rune {
			if r == '\t' || r == '\r' || r == '\n' {
				return ' '
			}
			return r
		}, v)
	}
	return v
}

func (g *gen) structFor(vi int, t *xsdc.ComplexType) *goStruct {
	comp := xsdc.ComponentOfComplex(t)
	return g.structOf[repKey{comp, g.rep.Classes[comp][vi]}]
}

// goKind is the Go type of a simple type in version vi.
func (g *gen) goKind(vi int, t *xsdc.SimpleType) (string, error) {
	k := xsdc.GoKind(t)
	switch {
	case k == "enum":
		en := g.enums[xsdc.ComponentOfSimple(t)]
		if en == nil {
			return "", fmt.Errorf("no enumeration type for %s", xsdc.ComponentOfSimple(t))
		}
		return en.name, nil
	case strings.HasPrefix(k, "[]"):
		return "", fmt.Errorf("list type %s is not implemented", xsdc.ComponentOfSimple(t))
	}
	return k, nil
}

func (g *gen) layout(st *goStruct) error {
	sh, err := xsdc.ShapeOf(st.rep)
	if err != nil {
		return err
	}
	st.shape = sh
	names := map[string]bool{"order": true}
	pick := func(n string) string {
		for i := 2; names[n]; i++ {
			n = n + strconv.Itoa(i)
		}
		names[n] = true
		return n
	}
	// reserve element names first so that an attribute of the same name
	// becomes NameAttr
	elemNames := map[string]bool{}
	for _, e := range sh.Elems {
		elemNames[ident(e.Name.Local)] = true
	}
	for i := range sh.Attrs {
		a := &sh.Attrs[i]
		k, err := g.goKind(st.vi, a.Type)
		if err != nil {
			return err
		}
		n := ident(a.Name.Local)
		if a.Name.NS == nsXML {
			n = "XML" + n
		}
		if elemNames[n] {
			n += "Attr"
		}
		f := &goField{name: pick(n), kind: fAttr, goType: k, ns: a.Name.NS, local: a.Name.Local, simple: a.Type, ptr: !a.Value, def: a.Default}
		st.fields = append(st.fields, f)
	}
	if sh.AnyAttr {
		st.fields = append(st.fields, &goField{name: pick("AnyAttrs"), kind: fAnyAttr, goType: "[]xml.Attr"})
	}
	if sh.Raw {
		st.fields = append(st.fields, &goField{name: pick("Content"), kind: fContent, goType: "[]*Node"})
		return nil
	}
	if sh.Value != nil {
		k, err := g.goKind(st.vi, sh.Value)
		if err != nil {
			return err
		}
		st.fields = append(st.fields, &goField{name: pick("Value"), kind: fValue, goType: k, simple: sh.Value})
	}
	order := 0
	for _, e := range sh.Elems {
		f := &goField{name: pick(ident(e.Name.Local)), kind: fElem, ns: e.Name.NS, local: e.Name.Local, many: e.Many, raw: e.Raw, order: order}
		order++
		switch {
		case e.Raw:
			f.goType = "*Node"
		case e.Element.Complex != nil:
			f.child = g.structFor(st.vi, e.Element.Complex)
			if f.child == nil {
				return fmt.Errorf("element %s: no struct for its type", e.Name)
			}
			f.goType = "*" + f.child.name
		default:
			k, err := g.goKind(st.vi, e.Element.Simple)
			if err != nil {
				return err
			}
			f.simple = e.Element.Simple
			f.goType = k
			f.ptr = !e.Many
		}
		st.fields = append(st.fields, f)
	}
	if sh.Any {
		st.fields = append(st.fields, &goField{name: pick("Any"), kind: fAny, goType: "[]*Node", order: order})
	}
	return nil
}

func (g *gen) versionList(vs []int) string {
	var parts []string
	for i := 0; i < len(vs); {
		j := i
		for j+1 < len(vs) && vs[j+1] == vs[j]+1 {
			j++
		}
		if j == i {
			parts = append(parts, "V"+g.c.Versions[vs[i]])
		} else {
			parts = append(parts, "V"+g.c.Versions[vs[i]]+" to V"+g.c.Versions[vs[j]])
		}
		i = j + 1
	}
	return strings.Join(parts, ", ")
}

func (g *gen) describe(comp xsdc.Component) string {
	if comp.Path != "" {
		return "the anonymous type of " + comp.Path
	}
	return "the complex type " + comp.Name.Local
}

func gofmt(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		lines := strings.Split(string(src), "\n")
		return nil, fmt.Errorf("%s: %v (%d lines)", name, err, len(lines))
	}
	return out, nil
}

func (g *gen) generate() (map[string][]byte, error) {
	files := map[string][]byte{}
	add := func(name string, src []byte, isGo bool) error {
		if isGo {
			var err error
			if src, err = gofmt(name, src); err != nil {
				return err
			}
		}
		files[name] = src
		return nil
	}
	types, err := g.genTypes()
	if err != nil {
		return nil, err
	}
	if err := add("gsdml/typed/zz_types.go", types, true); err != nil {
		return nil, err
	}
	tables, err := g.genTables()
	if err != nil {
		return nil, err
	}
	if err := add("gsdml/typed/zz_tables.go", tables, true); err != nil {
		return nil, err
	}
	if err := add("gsdml/typed/zz_versions.go", g.genVersions(), true); err != nil {
		return nil, err
	}
	samples, err := g.genSamples()
	if err != nil {
		return nil, err
	}
	if err := add("gsdml/typed/zz_samples_test.go", samples, true); err != nil {
		return nil, err
	}
	for vi := range g.c.Sets {
		pkg := "v" + digits(g.c.Versions[vi])
		src, err := g.genFacade(vi, pkg)
		if err != nil {
			return nil, err
		}
		if err := add("gsdml/versions/"+pkg+"/zz_facade.go", src, true); err != nil {
			return nil, err
		}
		if err := add("gsdml/versions/"+pkg+"/zz_facade_test.go", g.genFacadeTest(vi, pkg), true); err != nil {
			return nil, err
		}
	}
	if err := add("docs/GSDML-TYPED.md", g.genReport(), false); err != nil {
		return nil, err
	}
	return files, nil
}

// --- types, build and encode -------------------------------------------

func (g *gen) parser(f *goField) (string, error) {
	switch f.goType {
	case "string":
		switch f.simple.EffectiveWhiteSpace() {
		case "collapse":
			return "parseCollapse", nil
		case "replace":
			return "parseReplace", nil
		}
		return "parsePreserve", nil
	case "bool":
		return "parseBool", nil
	case "uint8", "uint16", "uint32", "uint64":
		return "parseUintN[" + f.goType + "]", nil
	case "int8", "int16", "int32", "int64":
		return "parseIntN[" + f.goType + "]", nil
	case "Integer", "Decimal":
		return "parseLexical[" + f.goType + "]", nil
	case "float64":
		return "parseFloat", nil
	}
	if _, ok := g.enumByName(f.goType); ok {
		return "parseEnum[" + f.goType + "]", nil
	}
	return "", fmt.Errorf("no parser for %s", f.goType)
}

func (g *gen) formatter(goType string) string {
	switch goType {
	case "bool":
		return "fmtBool"
	case "uint8", "uint16", "uint32", "uint64":
		return "fmtUint[" + goType + "]"
	case "int8", "int16", "int32", "int64":
		return "fmtInt[" + goType + "]"
	case "float64":
		return "fmtFloat"
	}
	return "fmtString[" + goType + "]"
}

func (g *gen) enumByName(n string) (*goEnum, bool) {
	for _, e := range g.enumList {
		if e.name == n {
			return e, true
		}
	}
	return nil, false
}

// literal is the Go literal of a default value of a field's type.
func (g *gen) literal(f *goField, v string) (string, error) {
	ws := f.simple.EffectiveWhiteSpace()
	switch f.goType {
	case "string":
		return strconv.Quote(normalize(v, ws)), nil
	case "bool":
		switch normalize(v, "collapse") {
		case "true", "1":
			return "true", nil
		case "false", "0":
			return "false", nil
		}
	case "uint8", "uint16", "uint32", "uint64":
		bits, _ := strconv.Atoi(f.goType[4:])
		u, err := strconv.ParseUint(strings.TrimPrefix(normalize(v, "collapse"), "+"), 10, bits)
		if err == nil {
			return strconv.FormatUint(u, 10), nil
		}
	case "int8", "int16", "int32", "int64":
		bits, _ := strconv.Atoi(f.goType[3:])
		i, err := strconv.ParseInt(strings.TrimPrefix(normalize(v, "collapse"), "+"), 10, bits)
		if err == nil {
			return strconv.FormatInt(i, 10), nil
		}
	case "float64":
		x := normalize(v, "collapse")
		if _, err := strconv.ParseFloat(x, 64); err == nil {
			return x, nil
		}
	case "Integer", "Decimal":
		return f.goType + "(" + strconv.Quote(normalize(v, "collapse")) + ")", nil
	default:
		if en, ok := g.enumByName(f.goType); ok {
			if c, ok := en.consts[normalize(v, ws)]; ok {
				return c, nil
			}
			return f.goType + "(" + strconv.Quote(normalize(v, ws)) + ")", nil
		}
	}
	return "", fmt.Errorf("default %q is not a %s", v, f.goType)
}

func (g *gen) genTypes() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package typed\n\nimport \"encoding/xml\"\n\n")
	b.WriteString("// The namespaces of the GSDML schemas and their imports.\nconst (\n")
	for _, ns := range []string{nsDeviceProfile, nsPrimitives, nsDsig, nsXades} {
		fmt.Fprintf(&b, "\t%s = %q\n", nsConst[ns], ns)
	}
	b.WriteString(")\n\n")
	b.WriteString("var _ = xml.Name{}\n\n")
	for _, en := range g.enumList {
		fmt.Fprintf(&b, "// %s is the enumeration %s (%s). Which values a version allows is in\n// its package gsdml/versions/vNNN and in its validation tables.\ntype %s string\n\n",
			en.name, en.comp.Name.Local, g.versionList(versionsOf(en.perVersion)), en.name)
		fmt.Fprintf(&b, "// The values of %s in any version.\nconst (\n", en.name)
		for _, v := range en.values {
			fmt.Fprintf(&b, "\t%s %s = %q\n", en.consts[v], en.name, v)
		}
		b.WriteString(")\n\n")
	}
	for _, st := range g.structs {
		if err := g.genStruct(&b, st); err != nil {
			return nil, fmt.Errorf("%s: %w", st.name, err)
		}
	}
	return b.Bytes(), nil
}

func versionsOf(per [][]string) []int {
	var out []int
	for i, p := range per {
		if p != nil {
			out = append(out, i)
		}
	}
	return out
}

func (g *gen) genStruct(b *bytes.Buffer, st *goStruct) error {
	sh := st.shape
	fmt.Fprintf(b, "// %s is %s\n// (%s).\n", st.name, g.describe(st.comp), g.versionList(st.versions))
	fmt.Fprintf(b, "type %s struct {\n", st.name)
	for _, f := range st.fields {
		switch f.kind {
		case fAttr:
			t := f.goType
			if f.ptr {
				t = "*" + t
			}
			req := ""
			if !f.ptr {
				req = ", required"
			}
			if f.def != nil {
				req = fmt.Sprintf(", default %q", *f.def)
			}
			fmt.Fprintf(b, "\t// %s is the attribute %s%s.\n\t%s %s\n", f.name, f.local, req, f.name, t)
		case fElem:
			t := f.goType
			switch {
			case f.many && f.raw:
				t = "[]*Node"
			case f.many && f.child != nil:
				t = "[]*" + f.child.name
			case f.many:
				t = "[]" + f.goType
			case f.simple != nil:
				t = "*" + f.goType
			}
			fmt.Fprintf(b, "\t// %s is the element %s.\n\t%s %s\n", f.name, f.local, f.name, t)
		case fValue:
			fmt.Fprintf(b, "\t// %s is the element's simple content.\n\t%s %s\n", f.name, f.name, f.goType)
		case fAny:
			fmt.Fprintf(b, "\t// %s is the wildcard content, verbatim.\n\t%s []*Node\n", f.name, f.name)
		case fAnyAttr:
			fmt.Fprintf(b, "\t// %s are the attributes of the attribute wildcard.\n\t%s []xml.Attr\n", f.name, f.name)
		case fContent:
			fmt.Fprintf(b, "\t// %s is the content, verbatim (mixed or any content).\n\t%s []*Node\n", f.name, f.name)
		}
	}
	if sh.Ordered {
		b.WriteString("\n\torder []pos\n")
	}
	b.WriteString("}\n\n")
	// defaults
	for _, f := range st.fields {
		if f.kind != fAttr || f.def == nil || !f.ptr {
			continue
		}
		lit, err := g.literal(f, *f.def)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "// %sOrDefault returns %s, or the schema default %q when it is absent.\nfunc (x *%s) %sOrDefault() %s { return orDefault(x.%s, %s) }\n\n",
			f.name, f.name, *f.def, st.name, f.name, f.goType, f.name, lit)
	}
	// build
	fmt.Fprintf(b, "func (x *%s) from(n *Node, b *builder) *%s {\n", st.name, st.name)
	if len(attrFields(st)) > 0 || sh.AnyAttr {
		b.WriteString("\tfor _, a := range n.Attrs {\n\t\tswitch a.Name {\n")
		for _, f := range attrFields(st) {
			p, err := g.parser(f)
			if err != nil {
				return err
			}
			fn := "attrValue"
			if f.ptr {
				fn = "attrPtr"
			}
			fmt.Fprintf(b, "\t\tcase xml.Name{Space: %s, Local: %q}:\n\t\t\tx.%s = %s(b, n, a, %s)\n", nsConst[f.ns], f.local, f.name, fn, p)
		}
		kept := "nil"
		if f := fieldOf(st, fAnyAttr); f != nil {
			kept = "&x." + f.name
		}
		fmt.Fprintf(b, "\t\tdefault:\n\t\t\tb.unknownAttr(n, a, %s)\n\t\t}\n\t}\n", kept)
	} else {
		b.WriteString("\tfor _, a := range n.Attrs {\n\t\tb.unknownAttr(n, a, nil)\n\t}\n")
	}
	switch {
	case sh.Raw:
		fmt.Fprintf(b, "\tx.%s = n.Children\n", fieldOf(st, fContent).name)
	case sh.Value != nil:
		f := fieldOf(st, fValue)
		p, err := g.parser(f)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\tx.%s = textValue(b, n, %s)\n", f.name, p)
		b.WriteString("\tfor _, k := range n.Children {\n\t\tif !k.IsText() {\n\t\t\tb.unknownElement(n, k, nil)\n\t\t}\n\t}\n")
	default:
		elems := elemFields(st)
		anyF := fieldOf(st, fAny)
		b.WriteString("\tfor _, k := range n.Children {\n\t\tif k.IsText() {\n\t\t\tcontinue\n\t\t}\n")
		if len(elems) == 0 {
			kept := "nil"
			if anyF != nil {
				kept = "&x." + anyF.name
			}
			if anyF != nil && sh.Ordered {
				fmt.Fprintf(b, "\t\tif b.unknownElement(n, k, %s) {\n\t\t\tx.order = append(x.order, position(%d, len(x.%s)))\n\t\t}\n", kept, anyF.order, anyF.name)
			} else {
				fmt.Fprintf(b, "\t\tb.unknownElement(n, k, %s)\n", kept)
			}
			b.WriteString("\t}\n")
			break
		}
		b.WriteString("\t\tswitch k.Name {\n")
		for _, f := range elems {
			fmt.Fprintf(b, "\t\tcase xml.Name{Space: %s, Local: %q}:\n", nsConst[f.ns], f.local)
			var val string
			switch {
			case f.raw:
				val = "k"
			case f.child != nil:
				val = fmt.Sprintf("new(%s).from(k, b)", f.child.name)
			default:
				p, err := g.parser(f)
				if err != nil {
					return err
				}
				if f.many {
					val = fmt.Sprintf("textValue(b, k, %s)", p)
				} else {
					val = fmt.Sprintf("textPtr(b, k, %s)", p)
				}
			}
			if f.many {
				fmt.Fprintf(b, "\t\t\tx.%s = append(x.%s, %s)\n", f.name, f.name, val)
			} else {
				fmt.Fprintf(b, "\t\t\tx.%s = %s\n", f.name, val)
			}
			if sh.Ordered {
				if f.many {
					fmt.Fprintf(b, "\t\t\tx.order = append(x.order, position(%d, len(x.%s)))\n", f.order, f.name)
				} else {
					fmt.Fprintf(b, "\t\t\tx.order = append(x.order, position(%d, 1))\n", f.order)
				}
			}
		}
		kept := "nil"
		if anyF != nil {
			kept = "&x." + anyF.name
		}
		if anyF != nil && sh.Ordered {
			fmt.Fprintf(b, "\t\tdefault:\n\t\t\tif b.unknownElement(n, k, %s) {\n\t\t\t\tx.order = append(x.order, position(%d, len(x.%s)))\n\t\t\t}\n", kept, anyF.order, anyF.name)
		} else {
			fmt.Fprintf(b, "\t\tdefault:\n\t\t\tb.unknownElement(n, k, %s)\n", kept)
		}
		b.WriteString("\t\t}\n\t}\n")
	}
	b.WriteString("\treturn x\n}\n\n")
	// encode
	inline := sh.Raw || sh.Value != nil
	fmt.Fprintf(b, "func (x *%s) encodeAs(e *encoder, ns, local string) {\n\te.start(ns, local, %v)\n", st.name, inline)
	for _, f := range attrFields(st) {
		ff := g.formatter(f.goType)
		if f.ptr {
			fmt.Fprintf(b, "\twriteAttr(e, %s, %q, x.%s, %s)\n", nsConst[f.ns], f.local, f.name, ff)
		} else {
			fmt.Fprintf(b, "\te.attr(%s, %q, %s(x.%s))\n", nsConst[f.ns], f.local, ff, f.name)
		}
	}
	if f := fieldOf(st, fAnyAttr); f != nil {
		fmt.Fprintf(b, "\tfor _, a := range x.%s {\n\t\te.attr(a.Name.Space, a.Name.Local, a.Value)\n\t}\n", f.name)
	}
	switch {
	case sh.Raw:
		fmt.Fprintf(b, "\te.content(x.%s)\n", fieldOf(st, fContent).name)
	case sh.Value != nil:
		f := fieldOf(st, fValue)
		fmt.Fprintf(b, "\te.text(%s(x.%s))\n", g.formatter(f.goType), f.name)
	case sh.Ordered:
		content := contentFields(st)
		var lens []string
		for _, f := range content {
			if f.many || f.kind == fAny {
				lens = append(lens, "len(x."+f.name+")")
			} else {
				lens = append(lens, "one(x."+f.name+" != nil)")
			}
		}
		fmt.Fprintf(b, "\tfor _, p := range effectiveOrder(x.order, []int{%s}) {\n\t\tswitch p.f {\n", strings.Join(lens, ", "))
		for _, f := range content {
			fmt.Fprintf(b, "\t\tcase %d:\n\t\t\t%s\n", f.order, g.encodeOneStmt(f))
		}
		b.WriteString("\t\t}\n\t}\n")
	default:
		for _, f := range contentFields(st) {
			fmt.Fprintf(b, "\t%s\n", g.encodeAllStmt(f))
		}
	}
	b.WriteString("\te.end(local)\n}\n\n")
	return nil
}

func (g *gen) encodeOneStmt(f *goField) string {
	ref := "x." + f.name
	if f.many || f.kind == fAny {
		ref += "[p.i]"
	}
	switch {
	case f.kind == fAny || f.raw:
		return fmt.Sprintf("nodeOne(e, %s)", ref)
	case f.child != nil:
		return fmt.Sprintf("encodeOne(e, %s, %q, %s)", nsConst[f.ns], f.local, ref)
	case f.many:
		return fmt.Sprintf("textOne(e, %s, %q, &%s, %s)", nsConst[f.ns], f.local, ref, g.formatter(f.goType))
	}
	return fmt.Sprintf("textOne(e, %s, %q, %s, %s)", nsConst[f.ns], f.local, ref, g.formatter(f.goType))
}

func (g *gen) encodeAllStmt(f *goField) string {
	switch {
	case f.kind == fAny:
		return fmt.Sprintf("nodeAll(e, x.%s)", f.name)
	case f.raw && f.many:
		return fmt.Sprintf("nodeAll(e, x.%s)", f.name)
	case f.raw:
		return fmt.Sprintf("nodeOne(e, x.%s)", f.name)
	case f.child != nil && f.many:
		return fmt.Sprintf("encodeAll(e, %s, %q, x.%s)", nsConst[f.ns], f.local, f.name)
	case f.child != nil:
		return fmt.Sprintf("encodeOne(e, %s, %q, x.%s)", nsConst[f.ns], f.local, f.name)
	case f.many:
		return fmt.Sprintf("textAll(e, %s, %q, x.%s, %s)", nsConst[f.ns], f.local, f.name, g.formatter(f.goType))
	}
	return fmt.Sprintf("textOne(e, %s, %q, x.%s, %s)", nsConst[f.ns], f.local, f.name, g.formatter(f.goType))
}

func attrFields(st *goStruct) []*goField {
	var out []*goField
	for _, f := range st.fields {
		if f.kind == fAttr {
			out = append(out, f)
		}
	}
	return out
}

func elemFields(st *goStruct) []*goField {
	var out []*goField
	for _, f := range st.fields {
		if f.kind == fElem {
			out = append(out, f)
		}
	}
	return out
}

func contentFields(st *goStruct) []*goField {
	var out []*goField
	for _, f := range st.fields {
		if f.kind == fElem || f.kind == fAny {
			out = append(out, f)
		}
	}
	return out
}

func fieldOf(st *goStruct, k fieldKind) *goField {
	for _, f := range st.fields {
		if f.kind == k {
			return f
		}
	}
	return nil
}
